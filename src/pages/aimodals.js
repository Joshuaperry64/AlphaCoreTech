        currentIdx = idx;
        imgEl.src = urls[currentIdx];
        countEl.textContent = `${currentIdx + 1} / ${urls.length}`;
        Array.from(thumbContainer.children).forEach((t, i) => {
          t.style.border = i === currentIdx ? '2px solid var(--accent)' : '2px solid transparent';
        });
