    guidanceScale: '7.0',
    guidanceImg: 4.0,
    stepsFastTxt: 10,
    stepsNormalTxt: 20,
    stepsFocusedTxt: 50,
    stepsFastImg: 8,
    stepsNormalImg: 17,
    stepsFocusedImg: 30
